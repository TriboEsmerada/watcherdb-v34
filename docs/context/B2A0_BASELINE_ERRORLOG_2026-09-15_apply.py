def main(argv):
    check = "--check" in argv
    preview = Path(argv[argv.index("--preview") + 1]) if "--preview" in argv else None
    base = preview or V1
    conteudo = base64.b64decode("".join(CONTEUDO_B64.split())).decode("utf-8")
    if hashlib.sha256(conteudo.encode("utf-8")).hexdigest() != SHA:
        print("[ABORT] conteudo embebido corrompido"); return 1
    destino = base / DEST
    if destino.exists():
        print("[ABORT] ja aplicado"); return 1
    chg = (base / CHANGELOG).read_bytes().decode("utf-8")
    eol = "\r\n" if "\r\n" in chg else "\n"
    anc = CHANGELOG_ANCORA.replace("\n", eol)
    if chg.count(anc) != 1:
        print("[ABORT] changelog V1: [Unreleased] nao unico"); return 1
    print(f"[ok] baseline {conteudo.count(chr(10))} linhas (sha confere); changelog; destino {base}")
    if check:
        print("--check OK. Nada escrito."); return 0
    destino.parent.mkdir(parents=True, exist_ok=True)
    destino.write_bytes(conteudo.replace("\n", "\r\n").encode("utf-8")); print(f"[new]   {DEST}")
    (base / CHANGELOG).write_bytes(chg.replace(anc, CHANGELOG_NOVO.replace("\n", eol), 1).encode("utf-8")); print(f"[write] {CHANGELOG}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
