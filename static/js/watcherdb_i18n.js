// Current language (load from localStorage or default to 'pt')
let _currentLang = localStorage.getItem('watcherdb_lang') || 'pt';

/**
 * Translation function - returns translated string for the given key.
 * Falls back to Portuguese, then to the key itself.
 */
function t(key, lang) {
    const activeLang = lang || _currentLang;
    const dict = WATCHERDB_I18N[activeLang];
    if (dict && dict[key] !== undefined) return dict[key];
    // Fallback to Portuguese
    if (activeLang !== 'pt' && WATCHERDB_I18N.pt && WATCHERDB_I18N.pt[key] !== undefined) {
        return WATCHERDB_I18N.pt[key];
    }
    return key;
}

/**
 * Translate a category name from Portuguese (as stored in code) to current language.
 */
const _categoryKeyMap = {
    'Disponibilidade': 'cat.disponibilidade',
    'Performance': 'cat.performance',
    'Espaço': 'cat.espaco',
    'Disco': 'cat.disco',
    'Backup': 'cat.backup',
    'Alta Disponibilidade': 'cat.alta_disponibilidade'
};

function tCategory(categoryName) {
    const key = _categoryKeyMap[categoryName];
    return key ? t(key) : categoryName;
}

/**
 * Set the current language, persist to localStorage, and update visible UI.
 */
function setLanguage(lang) {
    if (!WATCHERDB_I18N[lang]) return;
    _currentLang = lang;
    localStorage.setItem('watcherdb_lang', lang);
    document.documentElement.lang = lang === 'pt' ? 'pt-BR' : lang === 'es' ? 'es' : 'en';

    // Update selector visual
    const selector = document.getElementById('langSelector');
    if (selector) selector.value = lang;

    // Update UI elements
    applyLanguageToUI();
    console.log('[I18N] Language changed to:', lang);
}

/**
 * Apply language changes to visible UI elements without full page reload.
 */
function applyLanguageToUI() {
    // Search placeholder
    const searchInput = document.getElementById('searchInput');
    if (searchInput) searchInput.placeholder = t('header.search_placeholder');

    // Dashboard button
    const dashboardBtn = document.querySelector('[onclick="goToDashboardKPIs()"]');
    if (dashboardBtn) {
        const icon = dashboardBtn.querySelector('i');
        dashboardBtn.innerHTML = '';
        if (icon) dashboardBtn.appendChild(icon);
        dashboardBtn.appendChild(document.createTextNode(' ' + t('header.dashboard_kpis')));
        dashboardBtn.title = t('header.dashboard_title');
    }

    // Ping button title
    const pingBtn = document.getElementById('pingButton');
    if (pingBtn) pingBtn.title = t('header.ping_title');

    // Settings button title
    const settingsBtn = document.querySelector('[onclick="openSettingsModal()"]');
    if (settingsBtn) settingsBtn.title = t('header.settings');

    // Settings modal header
    const settingsHeader = document.querySelector('#settingsModal .modal-header h3');
    if (settingsHeader) settingsHeader.innerHTML = '<i class="fas fa-cog"></i> ' + t('modal.settings');

    // Service logs modal title
    const logsTitle = document.getElementById('serviceLogsModalTitle');
    if (logsTitle) logsTitle.innerHTML = '<i class="fas fa-scroll"></i> ' + t('modal.service_logs');

    // KPI Documentation modal title (if open)
    const kpiHelpTitle = document.getElementById('kpiHelpModalTitle');
    if (kpiHelpTitle) kpiHelpTitle.innerHTML = '<i class="fas fa-book" style="margin-right: 8px;"></i>' + t('doc.title');

    // KPI Help search placeholder
    const kpiHelpSearch = document.getElementById('kpiHelpSearch');
    if (kpiHelpSearch) kpiHelpSearch.placeholder = t('doc.search_placeholder');

    // KPI Help button (?) title
    const kpiHelpBtn = document.querySelector('[onclick="showKPIHelpModal()"]');
    if (kpiHelpBtn) kpiHelpBtn.title = t('doc.help_title');

    // Sidebar servers label
    const sidebarLabel = document.getElementById('sidebarServersLabel');
    if (sidebarLabel) sidebarLabel.textContent = t('sidebar.servers');

    // Translate all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        const translated = t(key);
        if (translated && translated !== key) {
            el.textContent = translated;
        }
    });

    // Update KPI_METADATA translations
    if (typeof updateKPIMetadataTranslations === 'function') {
        updateKPIMetadataTranslations();
    }

    // Re-render all open tabs to apply translations
    try {
        if (typeof openTabs !== 'undefined' && openTabs && openTabs.values) {
            for (const tab of openTabs.values()) {
                if (typeof refreshTab === 'function') {
                    refreshTab(tab.id);
                }
            }
        }
        // Also re-render main dashboard if visible (no tab)
        if (typeof renderDashboardCards === 'function') {
            const contentArea = document.getElementById('mainContentArea');
            if (contentArea && contentArea.querySelector('#kpi-dashboard-container')) {
                renderDashboardCards();
            }
        }
    } catch (e) {
        // openTabs or refreshTab may not be initialized yet
    }
}

